/**
 * E-ink: only ink and paper, no tones. Containers are filled with ink so that
 * selected and emphasized elements stay visible without shades of gray.
 */
internal fun eInkColors(dark: Boolean): ColorScheme {
    val ink = if (dark) Color.White else Color.Black
    val paper = if (dark) Color.Black else Color.White
    return lightColorScheme(
        primary = ink,
        onPrimary = paper,
        primaryContainer = ink,
        onPrimaryContainer = paper,
        inversePrimary = paper,
        secondary = ink,
        onSecondary = paper,
        secondaryContainer = ink,
        onSecondaryContainer = paper,
        tertiary = ink,
        onTertiary = paper,
        tertiaryContainer = ink,
        onTertiaryContainer = paper,
        background = paper,
        onBackground = ink,
        surface = paper,
        onSurface = ink,
        surfaceVariant = paper,
        onSurfaceVariant = ink,
        surfaceTint = paper,
        inverseSurface = ink,
        inverseOnSurface = paper,
        error = ink,
        onError = paper,
        errorContainer = ink,
        onErrorContainer = paper,
        outline = ink,
        outlineVariant = ink,
        scrim = Color.Black,
        surfaceBright = paper,
        surfaceDim = paper,
        surfaceContainerLowest = paper,
        surfaceContainerLow = paper,
        surfaceContainer = paper,
        surfaceContainerHigh = paper,
        surfaceContainerHighest = paper,
    )
}
